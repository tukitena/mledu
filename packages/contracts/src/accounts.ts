import { z } from 'zod'
import { AccountType, IsoDate, RowVersion } from './common'
import { OptionalPhone, PersonName } from './profile'

/** Account administration by Admin (AUTH-02–07). Admin targets are refused. */
export const AccountStatus = z.enum(['active', 'disabled', 'deleted'])
export type AccountStatus = z.infer<typeof AccountStatus>

export const AccountSummary = z.object({
  id: z.uuid(),
  email: z.string(),
  fullName: z.string(),
  accountType: AccountType,
  status: AccountStatus,
  mustChangePassword: z.boolean(),
  phone: z.string().nullable(),
  birthDate: IsoDate.nullable(),
  hasAvatar: z.boolean(),
  rowVersion: RowVersion,
  createdAt: z.string(),
  deletedAt: z.string().nullable(),
  deletedReason: z.string().nullable(),
})
export type AccountSummary = z.infer<typeof AccountSummary>

/** GET /v1/accounts */
export const ListAccountsQuery = z.object({
  search: z.string().trim().max(200).optional(),
  status: AccountStatus.optional(),
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
})
export type ListAccountsQuery = z.infer<typeof ListAccountsQuery>

export const AccountPage = z.object({
  items: z.array(AccountSummary),
  page: z.number().int().min(1),
  pageSize: z.number().int().min(1),
  total: z.number().int().min(0),
})
export type AccountPage = z.infer<typeof AccountPage>

/** POST /v1/accounts — new accounts are always of type User (AUTH-07). */
export const CreateAccountRequest = z.strictObject({
  email: z.string().trim().min(3).max(254),
  fullName: PersonName,
  phone: OptionalPhone.optional(),
  birthDate: IsoDate.nullable().optional(),
})
export type CreateAccountRequest = z.infer<typeof CreateAccountRequest>

/**
 * The temporary password is generated by the Worker and shown to the Admin
 * only in this response (AUTH-02). It is never stored in readable form.
 */
export const IssuedPasswordResponse = z.object({
  account: AccountSummary,
  temporaryPassword: z.string(),
})
export type IssuedPasswordResponse = z.infer<typeof IssuedPasswordResponse>

export const VersionedRequest = z.strictObject({ expectedVersion: RowVersion })
export type VersionedRequest = z.infer<typeof VersionedRequest>

/** PUT /v1/accounts/:id/type — only User <-> Receptionist. */
export const SetAccountTypeRequest = z.strictObject({
  accountType: z.enum(['user', 'receptionist']),
  expectedVersion: RowVersion,
})
export type SetAccountTypeRequest = z.infer<typeof SetAccountTypeRequest>

/** POST /v1/accounts/:id/delete — soft delete needs a reason (C.1.1). */
export const SoftDeleteAccountRequest = z.strictObject({
  reason: z.string().trim().min(1).max(1000),
  expectedVersion: RowVersion,
})
export type SoftDeleteAccountRequest = z.infer<typeof SoftDeleteAccountRequest>
